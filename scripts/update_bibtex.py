#!/usr/bin/env python3
"""Fetch citation BibTeX for each publication, preferring the published version.

Order of sources:
1. The publisher's record: DOI content negotiation for DOI links (ACM, Springer,
   TechRxiv), the ACL Anthology .bib for Anthology links, and otherwise a Crossref
   search for a published DOI whose title matches exactly.
2. arXiv's BibTeX, only when no published record exists.
Papers with neither keep the entry generated by build.py.

Run manually after adding papers: python3 scripts/update_bibtex.py
Results are written to data/bibtex.json; existing entries are refreshed.
"""
from pathlib import Path
import json,re,time,urllib.parse,urllib.request

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'data/bibtex.json'
HEADERS={'User-Agent':'tangjiakai.github.io bibtex updater (mailto:tangjiakai5704@gmail.com)'}

def fetch(url,accept=None):
    headers=dict(HEADERS)
    if accept: headers['Accept']=accept
    with urllib.request.urlopen(urllib.request.Request(url,headers=headers),timeout=60) as response:
        return response.read().decode('utf-8')

def normalize(title):
    return re.sub(r'[^a-z0-9]','',re.sub(r'<[^>]+>','',title).lower())

def tidy(entry):
    # Crossref returns a single line; put one field per line for reading and copying.
    entry=entry.strip()
    head,_,body=entry.partition(',')
    fields=[]
    depth=0
    current=''
    for char in body.rstrip('}').strip():
        if char=='{': depth+=1
        if char=='}': depth-=1
        if char==',' and depth==0:
            fields.append(current.strip()); current=''
        else:
            current+=char
    if current.strip(): fields.append(current.strip())
    return head.strip()+',\n'+',\n'.join('  '+field.replace(' = ','=',1) for field in fields if field)+'\n}'

def doi_from_link(link):
    match=re.search(r'(?:dl\.acm\.org/doi/(?:abs/|pdf/)?|link\.springer\.com/(?:chapter|article)/|techrxiv\.org/doi/(?:pdf/|full/)?)(10\.\d{4,}/[^?#]+)',link)
    return match.group(1).rstrip('/') if match else ''

def crossref_doi(title):
    query=urllib.parse.urlencode({'query.bibliographic':title,'rows':5,'select':'DOI,title,type'})
    items=json.loads(fetch('https://api.crossref.org/works?'+query))['message']['items']
    for item in items:
        if item.get('type')!='posted-content' and any(normalize(t)==normalize(title) for t in item.get('title',[])):
            return item['DOI']
    return ''

def arxiv_id(paper):
    match=re.search(r'arxiv\.org/(?:abs|pdf)/(\d{4}\.\d{4,5})',paper['link'])
    if match: return match.group(1)
    query=urllib.parse.urlencode({'search_query':'ti:"'+paper['title']+'"','max_results':3})
    feed=fetch('https://export.arxiv.org/api/query?'+query)
    for entry in re.findall(r'<entry>(.*?)</entry>',feed,re.S):
        title=' '.join(re.search(r'<title>(.*?)</title>',entry,re.S).group(1).split())
        if normalize(title)==normalize(paper['title']):
            return re.search(r'abs/(\d{4}\.\d{4,5})',entry).group(1)
    return ''

def published(paper):
    link=paper['link']
    if 'aclanthology.org/' in link:
        return fetch(link.rstrip('/')+'.bib').strip(),'ACL Anthology'
    doi=doi_from_link(link) or crossref_doi(paper['title'])
    if doi:
        try:
            entry=fetch('https://doi.org/'+doi,'application/x-bibtex; charset=utf-8')
        except urllib.error.HTTPError as error:
            # TechRxiv links omit the version suffix that the registered DOI carries.
            if error.code!=404 or 'techrxiv' not in doi: raise
            doi+='/v1'
            entry=fetch('https://doi.org/'+doi,'application/x-bibtex; charset=utf-8')
        return tidy(entry),'DOI '+doi
    return '',''

papers=json.loads((ROOT/'data/publications.json').read_text())
results={}
for paper in papers:
    entry,source='',''
    try:
        entry,source=published(paper)
        time.sleep(1)
        if not entry:
            identifier=arxiv_id(paper)
            time.sleep(3)
            if identifier:
                entry,source=fetch(f'https://arxiv.org/bibtex/{identifier}').strip(),'arXiv '+identifier
    except Exception as error:
        print(f"{paper['id']}: lookup failed ({error})")
    if entry:
        results[paper['id']]={'source':source,'bibtex':entry}
    print(f"{paper['id']:9} {source or 'generated by build.py':40} {paper['title'][:60]}")
OUT.write_text(json.dumps(results,ensure_ascii=False,indent=2)+'\n')
print(f'Saved {len(results)} of {len(papers)} entries to {OUT.relative_to(ROOT)}.')
